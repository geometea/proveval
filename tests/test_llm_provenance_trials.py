# ---------------------------------------------------------------------------
# 4. Manifest sizes: calculated, not hardcoded -- but pinned to the spec's
#    documented expectation too, so a silent drift in item counts is caught.
# ---------------------------------------------------------------------------

def expected_block_and_trial_counts(items, contrasts, n_regimes):
    n_pairs = len(items) * (len(items) - 1) // 2
    n_blocks = n_pairs * len(contrasts) * n_regimes
    return n_blocks, n_blocks * 4


def test_naturalistic_only_manifest_matches_spec_expected_counts(dims, items, contrasts):
    trials = build_context_pairwise_trials(dims, items, "naturalistic", choice_mode="forced", contrasts=contrasts)
    n_blocks, n_trials = expected_block_and_trial_counts(items, contrasts, 1)
    assert (n_blocks, n_trials) == (396, 1584)  # spec item 8's documented expectation
    by_block = lpt.assert_trials_are_well_formed(trials)
    assert len(trials) == n_trials
    assert len(by_block) == n_blocks


def test_both_regimes_manifest_matches_spec_expected_counts(dims, items, contrasts):
    trials = []
    for regime in EVALUATION_REGIMES:
        trials += build_context_pairwise_trials(dims, items, regime, choice_mode="forced", contrasts=contrasts)
    n_blocks, n_trials = expected_block_and_trial_counts(items, contrasts, len(EVALUATION_REGIMES))
    assert (n_blocks, n_trials) == (792, 3168)  # spec item 8's documented expectation
    by_block = lpt.assert_trials_are_well_formed(trials)
    assert len(trials) == n_trials
    assert len(by_block) == n_blocks


def test_default_evaluation_regime_is_naturalistic_only():
    assert lpt.DEFAULT_EVALUATION_REGIMES == ["naturalistic"]


