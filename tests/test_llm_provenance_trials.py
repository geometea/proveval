def test_main_writes_expected_trial_count_and_tags_every_trial_with_experiment_id(tmp_path, monkeypatch, capsys):
    out_path = tmp_path / "llm_provenance_trials.jsonl"
    monkeypatch.setattr(lpt, "TRIALS_FILE", str(out_path))
    monkeypatch.setattr("sys.argv", ["llm_provenance_trials.py"])

    lpt.main()

    lines = out_path.read_text().splitlines()
    assert len(lines) == 1584
    trials = [json.loads(line) for line in lines]
    assert all(t["experiment_id"] == lpt.EXPERIMENT_ID for t in trials)
    assert all(t["type"] == "context_pairwise" and t["choice_mode"] == "forced" for t in trials)

    out = capsys.readouterr().out
    assert "Blocks: 396" in out
    assert "Trials: 1584" in out


