def test_run_batch_limit_2_selects_exactly_two_complete_four_cell_blocks(dims, items, contrasts):
    trials = build_context_pairwise_trials(dims, items, "naturalistic", choice_mode="forced", contrasts=contrasts)
    selected = rb.select_trials(trials, None, None, None, None, None, limit=2)
    assert len(selected) == 8
    block_ids = {t["block_id"] for t in selected}
    assert len(block_ids) == 2
    for bid in block_ids:
        assert len([t for t in selected if t["block_id"] == bid]) == 4


def test_run_batch_limit_1_selects_exactly_one_complete_block(dims, items, contrasts):
    trials = build_context_pairwise_trials(dims, items, "naturalistic", choice_mode="forced", contrasts=contrasts)
    selected = rb.select_trials(trials, None, None, None, None, None, limit=1)
    assert len(selected) == 4
    assert len({t["block_id"] for t in selected}) == 1


def test_dedicated_trials_pass_existing_forced_choice_validation_with_no_new_validator(dims, items, contrasts):
    """The dedicated manifest's trials must validate through the SAME
    validate_pairwise_context_response_forced path as the general benchmark
    -- no bespoke validator for this experiment."""
    trials = _one_real_block(dims, items, contrasts)
    well_formed_response = json.dumps(
        {"plot_structure": "A", "prose_style": "B", "characterization": "A", "originality": "B", "overall_quality": "A"}
    )
    for t in trials:
        parsed, error = parse_and_validate(well_formed_response, t["type"], t.get("choice_mode"))
        assert error is None
        assert parsed["overall_quality"] == "A"


