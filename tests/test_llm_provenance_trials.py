def test_contrasts_file_has_exactly_six_rows(contrasts):
    assert len(contrasts) == 6 == len(lpt.PROVENANCE_LABELS) * (len(lpt.PROVENANCE_LABELS) - 1) // 2


def test_contrasts_are_exactly_all_c4_2_unordered_pairs(contrasts):
    expected_pairs = {frozenset(pair) for pair in itertools.combinations(lpt.PROVENANCE_LABELS, 2)}
    actual_pairs = {frozenset((c["a"], c["b"])) for c in contrasts}
    assert actual_pairs == expected_pairs


def test_contrasts_use_the_provenance_dimension_and_registered_values(dims, contrasts):
    for c in contrasts:
        assert c["dimension"] == "provenance"
        assert c["a"] in dims["provenance"]["values"]
        assert c["b"] in dims["provenance"]["values"]


def test_contrasts_do_not_repurpose_the_pre_existing_edited_value(contrasts):
    used_values = {v for c in contrasts for v in (c["a"], c["b"])}
    assert "ai_gemini_edited" not in used_values


def test_general_context_dimensions_still_has_all_pre_existing_provenance_values(dims):
    """Adding ai_gemini/ai_deepseek must be additive -- every pre-existing
    provenance value stays registered with its original wording untouched."""
    values = dims["provenance"]["values"]
    assert values["ai_claude"] == "This was generated by Claude."
    assert values["ai_chatgpt"] == "This was generated by ChatGPT."
    assert values["ai_gemini"] == "This was generated by Gemini."
    assert values["ai_deepseek"] == "This was generated by DeepSeek."
    assert "ai_gemini_edited" in values  # untouched, not repurposed


