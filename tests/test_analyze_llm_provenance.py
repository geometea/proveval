"""Tests for the standalone named-LLM provenance experiment's focused
analyser (analyze_llm_provenance.py).

Synthetic-fixture style, like tests/test_analyze_context.py's
TestDirectionalPairwiseEffect (make_full_block etc.) -- these tests build
observation dicts directly rather than running real trials/API calls, since
every effect-size calculation here is reused, unmodified, from
context_analysis_pairwise.py/context_analysis_io.py. What's under test is
this module's own thin composition: label attachment from structured
contrast fields, and the antisymmetric provenance matrix -- never a second
statistics implementation.
"""

import pytest

from context_analysis_common import RATING_FIELDS
from context_analysis_pairwise import (
    analyze_directional_pairwise_effects,
    analyze_pairwise_cell_rates,
    analyze_position_and_interaction_effects,
    summarize_directional_effects_by_contrast,
)

import analyze_llm_provenance as alp
import llm_provenance_trials as lpt


CLAUDE_VS_CHATGPT = {
    "id": "provenance_claude_vs_chatgpt", "dimension": "provenance",
    "a": "ai_claude", "b": "ai_chatgpt",
    "a_clause": "was generated by Claude", "b_clause": "was generated by ChatGPT",
    "hypothesis": "x",
}


def make_cell_obs(model, evaluation_regime, contrast_id, s1, s2, assignment, position, wins, n, prefix, choice_mode="forced"):
    """wins = number of replicates (out of n) where story_1 is the chosen story.
    Mirrors tests/test_analyze_context.py's helper of the same name exactly,
    since the underlying observation shape these functions read is unchanged
    by this focused experiment."""
    obs = {}
    for rep in range(1, n + 1):
        story_1_chosen = rep <= wins
        if position == "story1_as_a":
            story_a_id, story_b_id = s1, s2
            choice = "A" if story_1_chosen else "B"
        else:
            story_a_id, story_b_id = s2, s1
            choice = "B" if story_1_chosen else "A"
        obs[f"{prefix}_{rep}"] = {
            "type": "context_pairwise", "model": model, "evaluation_regime": evaluation_regime,
            "choice_mode": choice_mode, "contrast_id": contrast_id, "story_1_id": s1, "story_2_id": s2,
            "story_a_id": story_a_id, "story_b_id": story_b_id, "assignment": assignment, "position": position,
            "replicate_id": rep, "parsed_response": {f: choice for f in RATING_FIELDS},
            "experiment_id": lpt.EXPERIMENT_ID,
        }
    return obs


def make_full_block(model, evaluation_regime, contrast_id, s1, s2, fwd_a, fwd_b, flp_a, flp_b, n=10, prefix="x", choice_mode="forced"):
    obs = {}
    obs.update(make_cell_obs(model, evaluation_regime, contrast_id, s1, s2, "forward", "story1_as_a", fwd_a, n, f"{prefix}_fa", choice_mode))
    obs.update(make_cell_obs(model, evaluation_regime, contrast_id, s1, s2, "forward", "story2_as_a", fwd_b, n, f"{prefix}_fb", choice_mode))
    obs.update(make_cell_obs(model, evaluation_regime, contrast_id, s1, s2, "flipped", "story1_as_a", flp_a, n, f"{prefix}_pa", choice_mode))
    obs.update(make_cell_obs(model, evaluation_regime, contrast_id, s1, s2, "flipped", "story2_as_a", flp_b, n, f"{prefix}_pb", choice_mode))
    return obs


def pipeline(observations, contrasts=(CLAUDE_VS_CHATGPT,)):
    """Run exactly the same composition analyze_llm_provenance.main() runs,
    minus I/O, and return (by_contrast_rows, matrices, position_rows)."""
    labels_by_contrast_id = alp.contrast_labels(list(contrasts))
    directional_rows = alp.attach_labels(analyze_directional_pairwise_effects(observations), labels_by_contrast_id)
    by_contrast_rows = alp.attach_labels(summarize_directional_effects_by_contrast(directional_rows), labels_by_contrast_id)
    cell_rows = analyze_pairwise_cell_rates(observations)
    position_rows = alp.attach_labels(analyze_position_and_interaction_effects(cell_rows), labels_by_contrast_id)
    matrices = alp.build_provenance_matrix(by_contrast_rows)
    return directional_rows, by_contrast_rows, matrices, position_rows


