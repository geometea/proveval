# ---------------------------------------------------------------------------
# Fixture (a): Claude-attributed story always wins, balanced positions ->
# +1.0 directional effect; inverting the labels must flip the matrix sign.
# ---------------------------------------------------------------------------

class TestClaudeAlwaysWinsFixture:
    def test_directional_effect_is_plus_one(self):
        # forward: story_1 carries "a" (Claude) and always wins, both positions.
        # flipped: story_1 carries "b" (ChatGPT) and always loses, both positions.
        obs = make_full_block("m", "naturalistic", "provenance_claude_vs_chatgpt", "s1", "s2",
                               fwd_a=10, fwd_b=10, flp_a=0, flp_b=0)
        directional_rows, by_contrast_rows, matrices, _ = pipeline(obs)

        quality_row = next(r for r in by_contrast_rows if r["category"] == "overall_quality")
        assert quality_row["mean_directional_effect"] == pytest.approx(1.0)
        assert quality_row["label_a"] == "Claude"
        assert quality_row["label_b"] == "ChatGPT"

    def test_matrix_is_antisymmetric_and_matches_the_directional_effect(self):
        obs = make_full_block("m", "naturalistic", "provenance_claude_vs_chatgpt", "s1", "s2",
                               fwd_a=10, fwd_b=10, flp_a=0, flp_b=0)
        _, _, matrices, _ = pipeline(obs)
        matrix = matrices[("m", "naturalistic")]

        assert matrix["Claude"]["ChatGPT"] == pytest.approx(1.0)
        assert matrix["ChatGPT"]["Claude"] == pytest.approx(-1.0)
        assert matrix["Claude"]["Claude"] == 0.0
        assert matrix["ChatGPT"]["ChatGPT"] == 0.0

    def test_inverting_which_label_is_a_flips_the_matrix_sign(self):
        """Same underlying story preference (story_1 always wins when it
        carries whichever value is now labelled "a"), but with a/b swapped
        in the contrast definition itself -- the matrix must still be
        internally antisymmetric and the two runs must be exact mirrors."""
        inverted_contrast = {**CLAUDE_VS_CHATGPT, "a": "ai_chatgpt", "b": "ai_claude",
                              "a_clause": "was generated by ChatGPT", "b_clause": "was generated by Claude"}

        obs = make_full_block("m", "naturalistic", "provenance_claude_vs_chatgpt", "s1", "s2",
                               fwd_a=10, fwd_b=10, flp_a=0, flp_b=0)
        _, _, original_matrices, _ = pipeline(obs, contrasts=(CLAUDE_VS_CHATGPT,))
        _, _, inverted_matrices, _ = pipeline(obs, contrasts=(inverted_contrast,))

        original = original_matrices[("m", "naturalistic")]
        inverted = inverted_matrices[("m", "naturalistic")]
        assert original["Claude"]["ChatGPT"] == pytest.approx(-inverted["Claude"]["ChatGPT"])
        assert inverted["Claude"]["ChatGPT"] == pytest.approx(-1.0)
        assert inverted["ChatGPT"]["Claude"] == pytest.approx(1.0)


# ---------------------------------------------------------------------------
# Fixture (b): story preference never changes when labels swap -> 0.0 effect
# ---------------------------------------------------------------------------

class TestLabelInvariantPreferenceFixture:
    def test_directional_effect_is_zero(self):
        # 50/50 in every cell, regardless of which story carries which label.
        obs = make_full_block("m", "naturalistic", "provenance_claude_vs_chatgpt", "s1", "s2",
                               fwd_a=5, fwd_b=5, flp_a=5, flp_b=5)
        directional_rows, by_contrast_rows, matrices, _ = pipeline(obs)

        quality_row = next(r for r in by_contrast_rows if r["category"] == "overall_quality")
        assert quality_row["mean_directional_effect"] == pytest.approx(0.0)

        matrix = matrices[("m", "naturalistic")]
        assert matrix["Claude"]["ChatGPT"] == pytest.approx(0.0)
        assert matrix["ChatGPT"]["Claude"] == pytest.approx(0.0)


# ---------------------------------------------------------------------------
# Fixture (c): position-biased fixture -- the position analysis must
# identify the position effect separately from (and here, larger than) the
# pooled provenance effect.
# ---------------------------------------------------------------------------

class TestPositionBiasIsSeparatedFromProvenanceEffect:
    def test_position_effect_is_reported_and_distinct_from_the_pooled_provenance_effect(self):
        # forward: story1_as_a=8/10, story1_as_b=4/10; flipped: 6/10, 2/10
        # (identical to test_analyze_context.py's own position-confound
        # fixture -- same underlying phenomenon, now read through this
        # module's label-attaching composition instead of directly).
        obs = make_full_block("m", "naturalistic", "provenance_claude_vs_chatgpt", "s1", "s2",
                               fwd_a=8, fwd_b=4, flp_a=6, flp_b=2)
        directional_rows, by_contrast_rows, matrices, position_rows = pipeline(obs)

        quality_row = next(r for r in by_contrast_rows if r["category"] == "overall_quality")
        assert quality_row["mean_directional_effect"] == pytest.approx(0.2)

        position_row = next(r for r in position_rows if r["category"] == "overall_quality")
        assert position_row["label_a"] == "Claude"
        assert position_row["label_b"] == "ChatGPT"
        assert position_row["position_effect_pooled"] == pytest.approx(0.4)

        # The position effect is larger than -- and reported separately
        # from -- the pooled provenance-label effect that ends up in the matrix.
        assert abs(position_row["position_effect_pooled"]) > abs(quality_row["mean_directional_effect"])

        matrix = matrices[("m", "naturalistic")]
        # The matrix cell reflects only the pooled provenance effect (0.2),
        # never the larger position effect (0.4) -- position never leaks in.
        assert matrix["Claude"]["ChatGPT"] == pytest.approx(0.2)


# ---------------------------------------------------------------------------
# build_provenance_matrix / matrix_csv_rows: shape and defaults
# ---------------------------------------------------------------------------

def test_matrix_covers_all_four_labels_with_zero_diagonal_even_for_unmeasured_contrasts():
    obs = make_full_block("m", "naturalistic", "provenance_claude_vs_chatgpt", "s1", "s2",
                           fwd_a=10, fwd_b=10, flp_a=0, flp_b=0)
    _, by_contrast_rows, _, _ = pipeline(obs)
    matrix = alp.build_provenance_matrix(by_contrast_rows)[("m", "naturalistic")]

    assert set(matrix) == {"Claude", "ChatGPT", "Gemini", "DeepSeek"}
    for name in matrix:
        assert matrix[name][name] == 0.0
    # Gemini/DeepSeek never appeared in any observation -- their cells default
    # to 0.0 rather than raising, since pairwise_effects.csv (not the matrix)
    # is the source of truth for whether a cell was actually measured.
    assert matrix["Gemini"]["DeepSeek"] == 0.0


def test_matrix_csv_rows_produces_sixteen_tidy_rows_for_one_model_regime():
    obs = make_full_block("m", "naturalistic", "provenance_claude_vs_chatgpt", "s1", "s2",
                           fwd_a=10, fwd_b=10, flp_a=0, flp_b=0)
    _, by_contrast_rows, matrices, _ = pipeline(obs)
    rows = alp.matrix_csv_rows(matrices)
    assert len(rows) == 16  # 4x4, including the zero diagonal
    assert {"model", "evaluation_regime", "row_label", "column_label", "directional_effect"} <= set(rows[0])


