# 3. Prompt wording: plain A/B, "Passage" (never "Story"), no JSON, single
#    outcome, and the exact naturalistic-vs-suppression difference.
# ---------------------------------------------------------------------------

def _one_block(contrasts, items, regime="naturalistic"):
    story_1, story_2 = story_pairs(items[:2])[0]
    return ct.build_treatment_block(contrasts[0], story_1, story_2, regime)


def test_prompts_use_passage_never_story(contrasts, items):
    cells = _one_block(contrasts, items)
    for c in cells:
        assert "Passage A" in c["prompt"]
        assert "Passage B" in c["prompt"]
        assert "Story A" not in c["prompt"]
        assert "Story B" not in c["prompt"]


def test_prompts_ask_a_single_plain_ab_question_no_json(contrasts, items):
    cells = _one_block(contrasts, items)
    for c in cells:
        assert "Please answer A or B" in c["prompt"]
        assert "Return only JSON" not in c["prompt"]
        assert '"overall_quality"' not in c["prompt"]
        assert "plot_structure" not in c["prompt"]
        assert "Categories:" not in c["prompt"]


def test_naturalistic_and_suppression_prompts_differ_only_by_the_instruction(contrasts, items):
    naturalistic_cells = _one_block(contrasts, items, "naturalistic")
    suppression_cells = _one_block(contrasts, items, "text_only_invariance")
    by_key_nat = {(c["assignment"], c["position"]): c for c in naturalistic_cells}
    by_key_sup = {(c["assignment"], c["position"]): c for c in suppression_cells}

    for key in by_key_nat:
        nat, sup = by_key_nat[key], by_key_sup[key]
        assert nat["intro"] == sup["intro"]
        assert nat["context_a"] == sup["context_a"]
        assert nat["context_b"] == sup["context_b"]
        expected_sup_prompt = nat["prompt"].replace(
            f"{nat['intro']}\n\n", f"{nat['intro']}\n\n{ct.SUPPRESSION_INSTRUCTION}\n\n", 1
        )
        assert sup["prompt"] == expected_sup_prompt


def test_suppression_instruction_is_exactly_the_frozen_sentence(contrasts, items):
    assert ct.SUPPRESSION_INSTRUCTION == (
        "For this comparison, I'm only interested in the writing itself. "
        "Please base your judgment on the passages as written."
    )
    cells = _one_block(contrasts, items, "text_only_invariance")
    for c in cells:
        assert ct.SUPPRESSION_INSTRUCTION in c["prompt"]


def test_suppression_prompt_never_enumerates_the_treatment_family_list(contrasts, items):
    """The old wording used to explicitly enumerate authorship/source/
    reception/editing/opinion, and used the words context/bias/invariance/
    suppression/irrelevant -- none of that may appear in the prompt."""
    cells = _one_block(contrasts, items, "text_only_invariance")
    banned_terms = [
        "authorship", "source", "reception", "editing status", "asker's own opinion",
        "irrelevant", "context", "bias", "invariance", "suppress",
    ]
    for c in cells:
        lowered = c["prompt"].lower()
        for term in banned_terms:
            assert term not in lowered, f"{term!r} must not appear in the suppression prompt"


def test_baseline_prompt_has_no_contextual_claim():
    items_local = load_items()
    baseline_trials = ct.build_baseline_trials(items_local[:2])
    for t in baseline_trials:
        assert "Passage A" in t["prompt"] and "Passage B" in t["prompt"]
        assert t["prompt"].startswith(ct.BASELINE_INTRO)
        # None of the 5 contrasts' clauses can have leaked in.
        for a_clause, b_clause in FROZEN_CLAUSES.values():
            assert a_clause not in t["prompt"]
            assert b_clause not in t["prompt"]


