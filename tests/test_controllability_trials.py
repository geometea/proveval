def test_is_completed_ignores_a_result_saved_against_a_different_prompt_hash():
    records = [{"parsed_response": {"overall_quality": "A"}, "validation_error": None,
                "trial_meta": {"prompt_sha256": "old_hash"}}]
    assert rb.is_completed(records, expected_prompt_sha256="old_hash") is True
    assert rb.is_completed(records, expected_prompt_sha256="new_hash") is False


def test_is_completed_is_unaffected_for_trials_without_a_prompt_sha256():
    """Every trial type except this experiment has no prompt_sha256 at all
    -- passing None must reproduce the exact old behavior."""
    records = [{"parsed_response": {"x": 1}, "validation_error": None}]
    assert rb.is_completed(records) is True
    assert rb.is_completed(records, expected_prompt_sha256=None) is True
