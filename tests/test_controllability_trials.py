# 4. prompt_sha256: deterministic, matches the prompt, changes if the
#    prompt changes.
# ---------------------------------------------------------------------------

def test_prompt_sha256_matches_the_prompt(contrasts, items):
    cells = _one_block(contrasts, items)
    for c in cells:
        assert c["prompt_sha256"] == hashlib.sha256(c["prompt"].encode("utf-8")).hexdigest()


def test_prompt_sha256_differs_between_naturalistic_and_suppression(contrasts, items):
    naturalistic_cells = _one_block(contrasts, items, "naturalistic")
    suppression_cells = _one_block(contrasts, items, "text_only_invariance")
    nat_hashes = {c["prompt_sha256"] for c in naturalistic_cells}
    sup_hashes = {c["prompt_sha256"] for c in suppression_cells}
    assert nat_hashes.isdisjoint(sup_hashes)


def test_baseline_trials_carry_a_matching_prompt_sha256():
    items_local = load_items()
    baseline_trials = ct.build_baseline_trials(items_local[:2])
    for t in baseline_trials:
        assert t["prompt_sha256"] == hashlib.sha256(t["prompt"].encode("utf-8")).hexdigest()


